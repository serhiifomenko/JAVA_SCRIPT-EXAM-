// ## Техническое задание
//
// Создай сайт из трёх страниц:
//
//     * `index.html` — список пользователей;
// * `user-details.html` — подробная информация о пользователе и его посты;
// * `post-details.html` — подробная информация о посте и комментарии.

// ### 1. Страница `index.html`
//
// 1. Получи массив пользователей с помощью `fetch`:
//
// `https://jsonplaceholder.typicode.com/users`
//
// 2. Выведи всех пользователей на страницу.
//
// 3. Для каждого пользователя создай отдельную карточку, в которой покажи:
//
// * `id`;
// * `name`.
//
// 4. В каждой карточке добавь кнопку или ссылку **«Подробнее»**.
//
// 5. При нажатии должна открываться страница `user-details.html`. Через URL необходимо передать `id` выбранного пользователя, например:
//
// `user-details.html?id=1`

//
// ### 2. Страница `user-details.html`
//
// 1. Получи `id` пользователя из адресной строки.
//
// 2. Загрузи информацию об этом пользователе:
//
//     `https://jsonplaceholder.typicode.com/users/USER_ID`
//
// 3. Выведи всю информацию о пользователе без исключений, включая:
//
// * имя и username;
// * email и телефон;
// * сайт;
// * адрес;
// * географические координаты;
// * информацию о компании.
//
// 4. Под информацией добавь кнопку **«Posts of current user»**.
//
// 5. При нажатии на кнопку загрузи посты пользователя:
//
//     `https://jsonplaceholder.typicode.com/users/USER_ID/posts`
//
// 6. Выведи названия (`title`) всех его постов.
//
// 7. Для каждого поста создай отдельную карточку и добавь кнопку или ссылку **«Подробнее»**.
//
// 8. При нажатии должна открываться страница `post-details.html`. Через URL передай `id` выбранного поста, например:
//
// `post-details.html?id=5`
//

// ### 3. Страница `post-details.html`
//
// 1. Получи `id` поста из адресной строки.
//
// 2. Загрузи выбранный пост:
//
//     `https://jsonplaceholder.typicode.com/posts/POST_ID`
//
// 3. Выведи всю информацию о посте без исключений:
//
//     * `userId`;
// * `id`;
// * `title`;
// * `body`.
//
// 4. Затем загрузи комментарии этого поста:
//
//     `https://jsonplaceholder.typicode.com/posts/POST_ID/comments`
//
// 5. Под информацией о посте выведи все комментарии. Для каждого комментария покажи все его поля:
//
//     * `postId`;
// * `id`;
// * `name`;
// * `email`;
// * `body`.
//

// ## Требования к оформлению
//
// ### `index.html`
//
// * Карточки пользователей расположить по две в одном ряду.
// * Кнопку **«Подробнее»** разместить под информацией о пользователе.
//
// ### `user-details.html`
//
// * Большой блок с полной информацией о пользователе разместить сверху.
// * Кнопку **«Posts of current user»** расположить под ним.
// * Ширина кнопки — `90%` страницы.
// * Кнопка должна находиться по центру.
// * Карточки постов расположить по пять в одном ряду.
//
// ### `post-details.html`
//
// * Блок с полной информацией о посте разместить сверху.
// * Карточки комментариев расположить по четыре в одном ряду.
//
// ### Общие требования
//
// Все пользователи, посты и комментарии должны выглядеть как отдельные карточки. Для этого добавь им:
//
//     * фон;
// * внешние и внутренние отступы;
// * границы или тени;
// * закруглённые углы;
// * расстояние между карточками.


fetch('https://jsonplaceholder.typicode.com/users')
.then(response => response.json())
.then(users => {
    console.log(users);
    users.forEach(user => {
        const userBlock = document.createElement('div');
        userBlock.classList.add('block');
        const textBlock = document.createElement('p');
        textBlock.classList.add('text');

        const link = document.createElement('a');
        link.innerText = 'Подробнее';
        link.href = `../user/user-details.html?id=${user.id}`;

        textBlock.textContent = `
        ${user.id} 
        ${user.name}
        `
        userBlock.appendChild(textBlock);
        userBlock.appendChild(link);
        document.body.appendChild(userBlock);
        localStorage.setItem('user', JSON.stringify('users'));
    });

});


